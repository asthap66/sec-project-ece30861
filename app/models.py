"""SQLAlchemy Incident and Evidence models.

Owner: Srihari, with field review from Astha. Fields follow the Q5.2 schemas in
the pod contract (Phase 2 - Pod.pdf); the JSON names are camelCase
(discoveredAt), the database columns snake_case (discovered_at).

Design notes:
- Every timestamp is timezone-aware (TIMESTAMP WITH TIME ZONE) and stored as
  an instant; responses convert to UTC (REQ-14).
- The times a user supplies (discovered_at, collected_at) are kept separate
  from the times the system records (created_at, recorded_at). Phase 1 named
  mixing those up as the main risk for deadline calculations.
- Public IDs (INC-001, EVD-001) are generated by PostgreSQL from the row's own
  number, so two requests at the same moment can never get the same ID. They
  are fetched back on insert, so obj.public_id is set right after db.flush().
- Records are append-only (REQ-07): there is no update path in the API, and
  evidence can't be removed while it still points at its incident.
"""

from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    Computed,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.config import DESCRIPTION_MAX_LENGTH, SHORT_TEXT_MAX_LENGTH, TITLE_MAX_LENGTH
from app.db import Base

INCIDENT_STATUSES = ("OPEN", "NOT_MATERIAL", "MATERIAL_PENDING_FILING", "FILED")
EVIDENCE_CATEGORIES = ("TECHNICAL", "BUSINESS_IMPACT", "LEGAL", "OTHER")
DECISIONS = ("MATERIAL", "NOT_MATERIAL")

# Project data cleared by /reset and /test/setup, in one TRUNCATE (so child
# rows go with their parents). RESTART IDENTITY restarts INC/EVD/DEC numbering.
RESET_PROJECT_DATA = (
    "TRUNCATE TABLE decision_evidence, decisions, evidence, incidents RESTART IDENTITY"
)


def _public_id(prefix: str) -> Computed:
    """INC-001 ... INC-999, then INC-1000 (padded to 3 digits, never truncated)."""
    return Computed(
        f"'{prefix}-' || CASE WHEN id < 1000 THEN lpad(id::text, 3, '0') ELSE id::text END",
        persisted=True,
    )


def _one_of(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


class Incident(Base):
    __tablename__ = "incidents"
    __mapper_args__ = {"eager_defaults": True}  # fetch public_id/created_at on insert

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    public_id: Mapped[str] = mapped_column(String(32), _public_id("INC"), unique=True)

    title: Mapped[str] = mapped_column(String(TITLE_MAX_LENGTH))
    description: Mapped[str] = mapped_column(String(DESCRIPTION_MAX_LENGTH))
    discovered_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    reporter_name: Mapped[str] = mapped_column(String(SHORT_TEXT_MAX_LENGTH))
    # Phase 3 incidents stay OPEN; decisions and filings change it in Phase 4.
    status: Mapped[str] = mapped_column(String(32), default="OPEN", server_default="OPEN")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    evidence: Mapped[list["Evidence"]] = relationship(
        back_populates="incident", order_by="Evidence.id"
    )

    __table_args__ = (CheckConstraint(_one_of("status", INCIDENT_STATUSES), name="status_valid"),)


class Evidence(Base):
    __tablename__ = "evidence"
    __mapper_args__ = {"eager_defaults": True}  # fetch public_id/recorded_at on insert

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    public_id: Mapped[str] = mapped_column(String(32), _public_id("EVD"), unique=True)
    incident_id: Mapped[int] = mapped_column(
        ForeignKey("incidents.id", ondelete="RESTRICT"), index=True
    )

    category: Mapped[str] = mapped_column(String(32))
    summary: Mapped[str] = mapped_column(Text)
    source: Mapped[str] = mapped_column(String(SHORT_TEXT_MAX_LENGTH))
    collected_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    # Set by the server, never taken from the request (contract: response only).
    recorded_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    incident: Mapped[Incident] = relationship(back_populates="evidence")

    __table_args__ = (
        CheckConstraint(_one_of("category", EVIDENCE_CATEGORIES), name="category_valid"),
        # lets decision_evidence check evidence belongs to the decision's incident
        UniqueConstraint("id", "incident_id", name="evidence_id_incident_key"),
    )


class Decision(Base):
    """One human materiality decision (REQ-04). Append-only (REQ-07).

    The current decision is the incident's newest row by id (recording order,
    not determined_at). Status and deadline are not stored: DecisionService
    derives them on every read from this row and the shared calendar, so they
    can never disagree with it. incidents.status stays at its Phase 3 value.
    """

    __tablename__ = "decisions"
    __mapper_args__ = {"eager_defaults": True}  # fetch public_id/recorded_at on insert

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    public_id: Mapped[str] = mapped_column(String(32), _public_id("DEC"), unique=True)
    incident_id: Mapped[int] = mapped_column(
        ForeignKey("incidents.id", ondelete="RESTRICT"), index=True
    )

    decision: Mapped[str] = mapped_column(String(32))
    determined_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    decided_by: Mapped[str] = mapped_column(Text)
    rationale: Mapped[str] = mapped_column(Text)
    recorded_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    evidence_links: Mapped[list["DecisionEvidence"]] = relationship(
        order_by="DecisionEvidence.position"
    )

    __table_args__ = (
        CheckConstraint(_one_of("decision", DECISIONS), name="decision_valid"),
        UniqueConstraint("id", "incident_id", name="decisions_id_incident_key"),
    )


class DecisionEvidence(Base):
    """The evidence a decision cites, in the order submitted.

    position keeps the public evidenceIds list exactly as sent, including a
    repeated ID. Both composite foreign keys carry incident_id, so the
    database itself refuses evidence from another incident.
    """

    __tablename__ = "decision_evidence"

    decision_id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    position: Mapped[int] = mapped_column(Integer, primary_key=True)
    incident_id: Mapped[int] = mapped_column(BigInteger)
    evidence_id: Mapped[int] = mapped_column(BigInteger, index=True)

    __table_args__ = (
        ForeignKeyConstraint(
            ["decision_id", "incident_id"],
            ["decisions.id", "decisions.incident_id"],
            ondelete="RESTRICT",
            name="decision_evidence_decision_fkey",
        ),
        ForeignKeyConstraint(
            ["evidence_id", "incident_id"],
            ["evidence.id", "evidence.incident_id"],
            ondelete="RESTRICT",
            name="decision_evidence_evidence_fkey",
        ),
        CheckConstraint("position >= 0", name="position_nonnegative"),
    )


class TestSession(Base):
    """A session created by POST /test/setup (course testing interface).

    Stored in the database so a reused session ID is caught (409) even after a
    restart. The course spec says a session ID is never reused.
    """

    __tablename__ = "test_sessions"

    session_id: Mapped[str] = mapped_column(String(200), primary_key=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
